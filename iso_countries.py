# Codes the dn42 registry uses that are not ISO 3166-1 alpha-2 but map cleanly.
# `UK` is the common mistake for the United Kingdom, whose actual code is `GB`.
ALIASES = {
    "UK": "GB",
}


def normalize(value):
    """Return the ISO 3166-1 alpha-2 code for a registry or geofeed value.

    Returns None when the value is not a country code we can resolve, which
    covers supranational codes such as `EU` and outright errors such as `EN`.
    """
    if not value:
        return None
    code = value.strip().upper()
    code = ALIASES.get(code, code)
    return code if code in COUNTRIES else None


def name(code):
    """English short name for an already-normalized alpha-2 code."""
    return COUNTRIES[code]
